  <h1>About MicroFactory</h1>
  <p>MicroFactory is a comprehensive suite of powerful, client-side web tools designed for developers, designers, and everyday users. Our goal is to provide fast, reliable, and privacy-focused utilities without the bloat commonly associated with modern web applications.</p>

  <h2>Our Mission</h2>
  <p>We believe in the power of the open web. By leveraging modern browser APIs, we bring desktop-class tools straight to your browser. Our tools are designed to be offline-capable, highly accessible, and totally free to use. We prioritize performance and respect your time by ensuring our applications load instantly and perform complex tasks securely on your device.</p>

  <h2>Privacy First</h2>
  <p>Privacy is at the core of what we do. By processing data locally within your browser using technologies like WebAssembly, IndexedDB, and client-side JavaScript, we eliminate the need to upload your sensitive data to remote servers. What happens on your machine, stays on your machine.</p>

  <h2>Designed for Productivity</h2>
  <p>Our tools cover a wide range of use cases, including:</p>
  <ul>
    <li><strong>Data Conversion & Formatting:</strong> JSON formatting, XML parsing, CSV manipulation, and more.</li>
    <li><strong>Cryptography & Security:</strong> Hash generation, JWT debugging, password generation.</li>
    <li><strong>Design & Media:</strong> Color palettes, CSS generators, image and SVG optimization.</li>
    <li><strong>Development Utilities:</strong> Regex testing, Cron expression building, Base64 encoding.</li>
  </ul>

  <h2>Community Driven</h2>
  <p>MicroFactory is built by developers, for developers. We actively encourage community feedback, contributions, and suggestions. By building in public and listening to our users, we continuously evolve our tools to meet the real-world demands of modern workflows.</p>
